package io.github.cakeysama.ultraloot.guide;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import io.github.cakeysama.ultraloot.UltraLoot;
import io.github.cakeysama.ultraloot.mob.CardWear;
import io.github.cakeysama.ultraloot.mob.MobCardItem;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.Resource;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import org.jetbrains.annotations.Nullable;

import java.io.Reader;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Structure of the Ultra Loot Guide: chapters made of pages. Text lives in the lang files (translation keys), the
 * structure in {@code assets/ultraloot/guide/guide.json}; both are generated by {@code tools/lang/lang_guide.py}.
 * <p>
 * Pure data with no client classes, so the unit tests can check the shipped book (keys, items, recipes).
 */
public record GuideBookData(List<Chapter> chapters) {
    public static final ResourceLocation LOCATION = UltraLoot.id("guide/guide.json");
    public static final GuideBookData EMPTY = new GuideBookData(List.of());

    public record Chapter(String id, ResourceLocation icon, String titleKey, List<Page> pages) {
        public ItemStack iconStack() {
            return ItemSpec.stackOf(icon);
        }
    }

    /** One authored page: optional heading, optional recipe or icon row, then text (split over screens if long). */
    public record Page(String textKey, @Nullable String titleKey, @Nullable ResourceLocation recipe, List<ItemSpec> items) {}

    /**
     * An icon: {@code <item>}, {@code <item>@<entity>} (a Mob Card bound to that mob) and an optional {@code #<wear>}
     * suffix (a worn card, to show the durability bar).
     */
    public record ItemSpec(ResourceLocation item, @Nullable ResourceLocation entity, int wear) {
        public static ItemSpec parse(String spec) {
            String rest = spec;
            int wear = 0;
            int hash = rest.indexOf('#');
            if (hash >= 0) {
                wear = Math.max(0, Integer.parseInt(rest.substring(hash + 1)));
                rest = rest.substring(0, hash);
            }
            ResourceLocation entity = null;
            int at = rest.indexOf('@');
            if (at >= 0) {
                entity = ResourceLocation.parse(rest.substring(at + 1));
                rest = rest.substring(0, at);
            }
            return new ItemSpec(ResourceLocation.parse(rest), entity, wear);
        }

        public ItemStack toStack() {
            ItemStack stack = stackOf(item);
            if (entity != null && stack.getItem() instanceof MobCardItem) {
                Optional<EntityType<?>> type = BuiltInRegistries.ENTITY_TYPE.getOptional(entity);
                if (type.isPresent()) stack = MobCardItem.create(type.get());
            }
            if (wear > 0) CardWear.setWear(stack, wear);
            return stack;
        }

        /** The item, or a barrier when the id is unknown (a broken page stays visible instead of crashing). */
        static ItemStack stackOf(ResourceLocation id) {
            Item item = BuiltInRegistries.ITEM.getOptional(id).orElse(Items.BARRIER);
            return new ItemStack(item);
        }
    }

    /** Total number of authored pages. */
    public int pageCount() {
        return chapters.stream().mapToInt(c -> c.pages().size()).sum();
    }

    public static GuideBookData parse(JsonObject json) {
        List<Chapter> chapters = new ArrayList<>();
        for (JsonElement c : json.getAsJsonArray("chapters")) {
            JsonObject chapter = c.getAsJsonObject();
            List<Page> pages = new ArrayList<>();
            for (JsonElement p : chapter.getAsJsonArray("pages")) {
                JsonObject page = p.getAsJsonObject();
                List<ItemSpec> items = new ArrayList<>();
                if (page.has("items")) {
                    JsonArray array = page.getAsJsonArray("items");
                    for (JsonElement item : array) items.add(ItemSpec.parse(item.getAsString()));
                }
                pages.add(new Page(page.get("text").getAsString(),
                        page.has("title") ? page.get("title").getAsString() : null,
                        page.has("recipe") ? ResourceLocation.parse(page.get("recipe").getAsString()) : null,
                        List.copyOf(items)));
            }
            chapters.add(new Chapter(chapter.get("id").getAsString(), ResourceLocation.parse(chapter.get("icon").getAsString()),
                    chapter.get("title").getAsString(), List.copyOf(pages)));
        }
        return new GuideBookData(List.copyOf(chapters));
    }

    /** Reads the book from the resource packs; a missing or broken file gives an empty book and one log line. */
    public static GuideBookData load(ResourceManager resources) {
        Optional<Resource> resource = resources.getResource(LOCATION);
        if (resource.isEmpty()) {
            UltraLoot.LOGGER.warn("Ultra Loot guide not found: {}", LOCATION);
            return EMPTY;
        }
        try (Reader reader = resource.get().openAsReader()) {
            return parse(JsonParser.parseReader(reader).getAsJsonObject());
        } catch (Exception e) {
            UltraLoot.LOGGER.error("Ultra Loot guide could not be read: {}", LOCATION, e);
            return EMPTY;
        }
    }
}
