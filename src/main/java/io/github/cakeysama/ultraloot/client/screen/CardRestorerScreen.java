package io.github.cakeysama.ultraloot.client.screen;

import com.mojang.blaze3d.systems.RenderSystem;
import io.github.cakeysama.ultraloot.UltraLoot;
import io.github.cakeysama.ultraloot.config.Balance;
import io.github.cakeysama.ultraloot.machine.CardRestorerBlockEntity;
import io.github.cakeysama.ultraloot.machine.CardRestorerLogic;
import io.github.cakeysama.ultraloot.machine.CardRestorerStatus;
import io.github.cakeysama.ultraloot.menu.CardRestorerMenu;
import io.github.cakeysama.ultraloot.menu.MachineMenu;
import io.github.cakeysama.ultraloot.mob.MobCardItem;
import net.minecraft.ChatFormatting;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.screens.inventory.AbstractContainerScreen;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.player.Inventory;
import net.minecraft.world.inventory.Slot;

import java.util.ArrayList;
import java.util.List;

/**
 * Card Restorer screen: graphite machine panel with a copper accent, FE bar, status (indicator shape + colour +
 * text), input -> output slots with a status arrow, an integrity bar for the card in the input and four info rows.
 * All values come from the menu's synced {@link net.minecraft.world.inventory.ContainerData}.
 * <p>
 * Status classes follow docs/UI_UX_GUIDELINES.md: RUNNING = processing (cyan, filled square), IDLE = inactive
 * (gray, hollow square), NO_ENERGY and OUTPUT_FULL = warning (amber, exclamation mark).
 */
public class CardRestorerScreen extends AbstractContainerScreen<CardRestorerMenu> {
    private static final ResourceLocation PANEL = UltraLoot.id("textures/gui/card_restorer.png");
    public static final int ACCENT = 0xFFD9824A;

    // Sprites on card_restorer.png (outside the 176x202 panel), generated by tools/generate_restorer_assets.py.
    private static final int FILL_U = 0;
    private static final int FILL_INTACT_V = 204;
    private static final int FILL_DECAYING_V = 212;
    private static final int FILL_CORRUPTED_V = 220;
    private static final int FILL_W = 128;
    private static final int FILL_H = 7;
    private static final int ARROW_EMPTY_U = 130;
    private static final int ARROW_PROCESSING_U = 156;
    private static final int ARROW_WARNING_U = 182;
    private static final int ARROW_V = 204;
    private static final int ARROW_W = 24;
    private static final int ARROW_H = 16;
    private static final int ARROW_CYCLE_TICKS = 20;

    // Layout (panel-relative).
    private static final int ENERGY_X = 9;
    private static final int BAR_Y = 20;
    private static final int BAR_INNER = 86;
    private static final int TEXT_X = 30;
    private static final int TEXT_WIDTH = 136;
    private static final int STATUS_Y = 21;
    private static final int SEPARATOR_Y = 33;
    private static final int ARROW_X = 84;
    private static final int ARROW_Y = 41;
    private static final int INTEGRITY_Y = 62;
    private static final int INTEGRITY_W = 108;
    private static final int ROW_MOB_Y = 75;
    private static final int ROW_WEAR_Y = 85;
    private static final int ROW_COST_Y = 95;
    private static final int ROW_TIME_Y = 105;

    private boolean statusCut;

    public CardRestorerScreen(CardRestorerMenu menu, Inventory inventory, Component title) {
        super(menu, inventory, title);
        this.imageWidth = MachineMenu.GUI_WIDTH;
        this.imageHeight = MachineMenu.GUI_HEIGHT;
    }

    // ---- Classification ----------------------------------------------------------------------------

    private static GuiDraw.StatusClass statusClass(CardRestorerStatus status) {
        return switch (status) {
            case RUNNING -> GuiDraw.StatusClass.PROCESSING;
            case IDLE -> GuiDraw.StatusClass.INACTIVE;
            case NO_ENERGY, OUTPUT_FULL -> GuiDraw.StatusClass.WARNING;
        };
    }

    private static int statusColor(CardRestorerStatus status) {
        return switch (statusClass(status)) {
            case PROCESSING -> GuiDraw.PROCESSING;
            case INACTIVE -> GuiDraw.INACTIVE;
            case WARNING -> GuiDraw.WARN;
            case BLOCKED -> GuiDraw.BAD;
        };
    }

    private enum CardState { INTACT, DECAYING, CORRUPTED }

    private CardState cardState() {
        float decay = menu.decay();
        if (decay <= 0f) return CardState.INTACT;
        return decay >= 1f ? CardState.CORRUPTED : CardState.DECAYING;
    }

    private static int cardStateColor(CardState state) {
        return switch (state) {
            case INTACT -> GuiDraw.GOOD;
            case DECAYING -> GuiDraw.WARN;
            case CORRUPTED -> GuiDraw.BAD;
        };
    }

    private boolean hasCard() {
        return !menu.inputCard().isEmpty();
    }

    private Component mobName() {
        return MobCardItem.getEntityType(menu.inputCard()).map(EntityType::getDescription)
                .orElseGet(() -> Component.translatable("ultraloot.gui.restorer.no_card"));
    }

    // ---- Rendering --------------------------------------------------------------------------------------

    @Override
    public void render(GuiGraphics graphics, int mouseX, int mouseY, float partialTick) {
        super.render(graphics, mouseX, mouseY, partialTick);
        if (!menu.getCarried().isEmpty()) return;
        if (hoveredSlot != null && hoveredSlot.hasItem()) {
            renderTooltip(graphics, mouseX, mouseY);
            return;
        }
        List<Component> tooltip = hoveredSlot != null ? slotHint(hoveredSlot) : tooltipAt(mouseX - leftPos, mouseY - topPos);
        if (!tooltip.isEmpty()) graphics.renderComponentTooltip(font, tooltip, mouseX, mouseY);
    }

    @Override
    protected void renderBg(GuiGraphics graphics, float partialTick, int mouseX, int mouseY) {
        graphics.pose().pushPose();
        graphics.pose().translate(leftPos, topPos, 0);
        graphics.blit(PANEL, 0, 0, 0, 0, imageWidth, imageHeight);

        // FE bar.
        GuiSprites.BAR_FRAME.draw(graphics, ENERGY_X, BAR_Y);
        GuiSprites.ENERGY_FILL.drawBottom(graphics, ENERGY_X + 1, BAR_Y + 1, Math.round((float) menu.energy() / menu.energyMax() * BAR_INNER));

        // Status: indicator shape + colour + text.
        CardRestorerStatus status = menu.status();
        int color = statusColor(status);
        statusIndicator(graphics, status, TEXT_X, STATUS_Y);
        statusCut = GuiDraw.trimmed(graphics, font, Component.translatable(status.translationKey()), TEXT_X + 10, STATUS_Y, TEXT_WIDTH - 10, color);
        graphics.fill(TEXT_X, SEPARATOR_Y, TEXT_X + TEXT_WIDTH, SEPARATOR_Y + 1, GuiDraw.SEPARATOR);

        // Slots and the arrow between them.
        for (Slot slot : List.of(menu.slots.get(CardRestorerBlockEntity.INPUT), menu.slots.get(CardRestorerBlockEntity.OUTPUT))) {
            GuiSprites.SLOT.draw(graphics, slot.x - 1, slot.y - 1);
        }
        if (!hasCard()) {
            Slot input = menu.slots.get(CardRestorerBlockEntity.INPUT);
            GuiSprites.GHOST_MOB_CARD.draw(graphics, input.x, input.y);
        }
        renderArrow(graphics, status);

        // Integrity bar of the input card.
        GuiDraw.inset(graphics, TEXT_X, INTEGRITY_Y, INTEGRITY_W, FILL_H + 2);
        CardState state = cardState();
        if (hasCard()) {
            int v = switch (state) {
                case INTACT -> FILL_INTACT_V;
                case DECAYING -> FILL_DECAYING_V;
                case CORRUPTED -> FILL_CORRUPTED_V;
            };
            int filled = Math.round(Mth.clamp(menu.integrity(), 0f, 1f) * (INTEGRITY_W - 2));
            blit(graphics, TEXT_X + 1, INTEGRITY_Y + 1, FILL_U, v, Math.min(filled, FILL_W), FILL_H);
        }
        String percent = hasCard() ? GuiFormat.percent(menu.integrity()) : "-";
        graphics.drawString(font, percent, TEXT_X + TEXT_WIDTH - font.width(percent), INTEGRITY_Y + 1,
                hasCard() ? cardStateColor(state) : GuiDraw.DIM, false);

        // Info rows.
        int wear = menu.wear();
        GuiDraw.row(graphics, font, Component.translatable("ultraloot.gui.mob"), mobName(), TEXT_X, ROW_MOB_Y, TEXT_WIDTH,
                hasCard() ? GuiDraw.TEXT : GuiDraw.DIM);
        GuiDraw.row(graphics, font, Component.translatable("ultraloot.gui.restorer.wear"),
                hasCard() ? GuiFormat.fraction(wear, menu.maxWear()) : Component.literal("-"), TEXT_X, ROW_WEAR_Y, TEXT_WIDTH,
                hasCard() ? cardStateColor(state) : GuiDraw.DIM);
        GuiDraw.row(graphics, font, Component.translatable("ultraloot.gui.restorer.cost"),
                hasCard() ? GuiFormat.energy(menu.costPerWear()) : Component.literal("-"), TEXT_X, ROW_COST_Y, TEXT_WIDTH,
                hasCard() ? GuiDraw.TEXT : GuiDraw.DIM);
        GuiDraw.row(graphics, font, Component.translatable("ultraloot.gui.restorer.time_left"),
                hasCard() && wear > 0 ? GuiFormat.seconds(CardRestorerLogic.ticksToFinish(wear, menu.wearPerTick())) : Component.literal("-"),
                TEXT_X, ROW_TIME_Y, TEXT_WIDTH, hasCard() && wear > 0 ? GuiDraw.TEXT : GuiDraw.DIM);
        graphics.pose().popPose();
    }

    @Override
    protected void renderLabels(GuiGraphics graphics, int mouseX, int mouseY) {
        GuiDraw.trimmed(graphics, font, title, 9, 5, imageWidth - 18, ACCENT);
    }

    /** 7x7 indicator: the shape encodes the status class, the colour reinforces it (same shapes as GuiDraw). */
    private static void statusIndicator(GuiGraphics graphics, CardRestorerStatus status, int x, int y) {
        int color = statusColor(status);
        graphics.fill(x, y, x + 7, y + 7, 0xFF101216);
        switch (statusClass(status)) {
            case PROCESSING -> graphics.fill(x + 1, y + 1, x + 6, y + 6, color);
            case INACTIVE -> {
                graphics.fill(x + 1, y + 1, x + 6, y + 2, color);
                graphics.fill(x + 1, y + 5, x + 6, y + 6, color);
                graphics.fill(x + 1, y + 2, x + 2, y + 5, color);
                graphics.fill(x + 5, y + 2, x + 6, y + 5, color);
            }
            case WARNING -> {
                graphics.fill(x + 3, y + 1, x + 4, y + 4, color);
                graphics.fill(x + 3, y + 5, x + 4, y + 6, color);
            }
            case BLOCKED -> {
                for (int i = 1; i < 6; i++) {
                    graphics.fill(x + i, y + i, x + i + 1, y + i + 1, color);
                    graphics.fill(x + 6 - i, y + i, x + 7 - i, y + i + 1, color);
                }
            }
        }
    }

    /** Empty arrow while idle/unpowered, cyan sweep while repairing, amber when the output is occupied. */
    private void renderArrow(GuiGraphics graphics, CardRestorerStatus status) {
        blit(graphics, ARROW_X, ARROW_Y, ARROW_EMPTY_U, ARROW_V, ARROW_W, ARROW_H);
        if (status == CardRestorerStatus.RUNNING) {
            long time = minecraft != null && minecraft.level != null ? minecraft.level.getGameTime() : 0L;
            int filled = (int) ((time % ARROW_CYCLE_TICKS) + 1) * ARROW_W / ARROW_CYCLE_TICKS;
            blit(graphics, ARROW_X, ARROW_Y, ARROW_PROCESSING_U, ARROW_V, filled, ARROW_H);
        } else if (status == CardRestorerStatus.OUTPUT_FULL) {
            blit(graphics, ARROW_X, ARROW_Y, ARROW_WARNING_U, ARROW_V, ARROW_W, ARROW_H);
        }
    }

    private static void blit(GuiGraphics graphics, int x, int y, int u, int v, int width, int height) {
        if (width <= 0 || height <= 0) return;
        RenderSystem.enableBlend();
        RenderSystem.defaultBlendFunc();
        graphics.blit(PANEL, x, y, u, v, width, height);
        RenderSystem.disableBlend();
    }

    // ---- Tooltips -------------------------------------------------------------------------------------

    private static boolean isOver(double mx, double my, int x, int y, int width, int height) {
        return mx >= x && mx < x + width && my >= y && my < y + height;
    }

    private List<Component> tooltipAt(double mx, double my) {
        if (isOver(mx, my, ENERGY_X, BAR_Y, GuiSprites.BAR_FRAME.width(), GuiSprites.BAR_FRAME.height())) return energyTooltip();
        CardRestorerStatus status = menu.status();
        if (isOver(mx, my, TEXT_X, STATUS_Y - 1, TEXT_WIDTH, 9) || isOver(mx, my, ARROW_X, ARROW_Y, ARROW_W, ARROW_H)) {
            List<Component> lines = new ArrayList<>();
            if (statusCut || isOver(mx, my, ARROW_X, ARROW_Y, ARROW_W, ARROW_H)) {
                lines.add(Component.translatable(status.translationKey()).withColor(statusColor(status)));
            }
            lines.add(Component.translatable(status.descriptionKey()).withStyle(ChatFormatting.GRAY));
            return lines;
        }
        if (!hasCard()) return List.of();
        if (isOver(mx, my, TEXT_X, INTEGRITY_Y, TEXT_WIDTH, FILL_H + 2) || isOver(mx, my, TEXT_X, ROW_WEAR_Y - 1, TEXT_WIDTH, 10)) {
            return integrityTooltip();
        }
        if (isOver(mx, my, TEXT_X, ROW_COST_Y - 1, TEXT_WIDTH, 10)) {
            return List.of(Component.translatable("ultraloot.gui.restorer.cost.desc").withStyle(ChatFormatting.GRAY),
                    Component.translatable("ultraloot.gui.restorer.energy_to_finish",
                            GuiFormat.energy(CardRestorerLogic.energyToFinish(menu.wear(), menu.costPerWear()))).withStyle(ChatFormatting.GRAY));
        }
        if (isOver(mx, my, TEXT_X, ROW_TIME_Y - 1, TEXT_WIDTH, 10)) {
            return List.of(Component.translatable("ultraloot.gui.restorer.rate", GuiFormat.number(menu.wearPerTick()))
                    .withStyle(ChatFormatting.GRAY));
        }
        return List.of();
    }

    private List<Component> energyTooltip() {
        List<Component> lines = new ArrayList<>();
        lines.add(Component.translatable("ultraloot.gui.energy"));
        lines.add(Component.translatable("ultraloot.gui.unit.fe", GuiFormat.fraction(menu.energy(), menu.energyMax())).withStyle(ChatFormatting.GRAY));
        lines.add(Component.translatable("ultraloot.gui.restorer.cost_line",
                hasCard() ? GuiFormat.energy(menu.costPerWear()) : Component.literal("-")).withStyle(ChatFormatting.GRAY));
        lines.add(Component.translatable("ultraloot.gui.restorer.input_rate", GuiFormat.energy(Balance.RESTORER_ENERGY_INPUT))
                .withStyle(ChatFormatting.GRAY));
        return lines;
    }

    private List<Component> integrityTooltip() {
        CardState state = cardState();
        String key = "ultraloot.gui.restorer.card_state." + state.name().toLowerCase(java.util.Locale.ROOT);
        return List.of(Component.translatable("ultraloot.gui.restorer.integrity", GuiFormat.percent(menu.integrity())),
                Component.translatable(key).withColor(cardStateColor(state)),
                Component.translatable("ultraloot.gui.restorer.wear_line", GuiFormat.fraction(menu.wear(), menu.maxWear()))
                        .withStyle(ChatFormatting.GRAY));
    }

    private List<Component> slotHint(Slot slot) {
        if (slot.index == CardRestorerBlockEntity.INPUT) {
            return List.of(Component.translatable("ultraloot.gui.restorer.input"),
                    Component.translatable("ultraloot.gui.restorer.input.hint").withStyle(ChatFormatting.GRAY));
        }
        if (slot.index == CardRestorerBlockEntity.OUTPUT) {
            return List.of(Component.translatable("ultraloot.gui.restorer.output"),
                    Component.translatable("ultraloot.gui.restorer.output.hint").withStyle(ChatFormatting.GRAY));
        }
        return List.of();
    }
}
